# Tool 3: บันทึกอารมณ์ของ User
# --------------------------------------------------
@mcp.tool()
def log_mood(mood: str, note: str = "") -> dict:
    """
    บันทึกอารมณ์ของ User ลงไฟล์ mood_log.json เพื่อติดตามแนวโน้ม

    Args:
        mood: คำอธิบายอารมณ์ เช่น "เครียด", "เหนื่อย", "ดีขึ้น", "สุข"
        note: บันทึกเพิ่มเติม (optional)
    """
    log_entry = {
        "timestamp": datetime.now().isoformat(),
        "mood": mood,
        "note": note
    }

    log_path = "data/mood_log.json"
    try:
        with open(log_path, "r", encoding="utf-8") as f:
            logs = json.load(f)
    except (FileNotFoundError, json.JSONDecodeError):
        logs = []

    logs.append(log_entry)

    with open(log_path, "w", encoding="utf-8") as f:
        json.dump(logs, f, ensure_ascii=False, indent=2)

    return {
        "status": "success",
        "message": f"บันทึกอารมณ์ '{mood}' เรียบร้อยแล้ว",
        "total_entries": len(logs)
    }


